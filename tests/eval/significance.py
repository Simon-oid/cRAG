#!/usr/bin/env python3
"""Confidence intervals and paired significance for cRAG's BEIR runs.

A mean nDCG@10 per mode cannot say whether hybrid really beats cosine:
with a few hundred queries a 0.005 gap can be noise. This script reads
the per-query CSVs written by `eval_beir --per-query` (one per dataset)
and reports, per dataset:

  - each mode's mean with a 95% bootstrap confidence interval
    (queries resampled with replacement);
  - for hybrid vs cosine and hybrid vs bm25, the mean paired difference,
    its 95% paired-bootstrap interval, and a two-sided paired
    permutation (sign-flip) test p-value.

Paired, because every mode answers the same queries: the per-query
difference removes the query difficulty that dominates the variance.

Standard library only, fixed seed, so the report is reproducible.

    python3 tests/eval/significance.py tests/eval/perquery_*.csv [--md OUT]
"""

from __future__ import annotations

import argparse
import csv
import random
import re
import sys
from collections import defaultdict
from pathlib import Path

B = 10_000          # bootstrap resamples / permutation rounds
SEED = 20261109
METRIC = "ndcg10"
COMPARISONS = [("hybrid", "cosine"), ("hybrid", "bm25")]


def load(path: Path) -> dict[str, dict[str, float]]:
    """mode -> qid -> metric."""
    by_mode: dict[str, dict[str, float]] = defaultdict(dict)
    with path.open() as f:
        for row in csv.DictReader(f):
            by_mode[row["mode"]][row["qid"]] = float(row[METRIC])
    return by_mode


def mean(xs: list[float]) -> float:
    return sum(xs) / len(xs)


def bootstrap_ci(xs: list[float], rng: random.Random) -> tuple[float, float]:
    n = len(xs)
    means = sorted(mean([xs[rng.randrange(n)] for _ in range(n)]) for _ in range(B))
    return means[int(0.025 * B)], means[int(0.975 * B) - 1]


def permutation_p(diffs: list[float], rng: random.Random) -> float:
    """Two-sided paired sign-flip test of mean(diffs) == 0."""
    observed = abs(mean(diffs))
    hits = 0
    for _ in range(B):
        s = sum(d if rng.random() < 0.5 else -d for d in diffs) / len(diffs)
        if abs(s) >= observed - 1e-12:
            hits += 1
    return (hits + 1) / (B + 1)


def dataset_label(path: Path) -> str:
    m = re.match(r"perquery_([^_]+)_(.+)\.csv$", path.name)
    return f"{m.group(1)} ({m.group(2)})" if m else path.stem


def report(path: Path) -> list[str]:
    rng = random.Random(SEED)
    by_mode = load(path)
    modes = [m for m in ("cosine", "bm25", "hybrid", "rerank") if m in by_mode]
    # Only queries every mode answered, so all comparisons are paired.
    common = sorted(set.intersection(*(set(by_mode[m]) for m in modes)))
    lines = [f"### {dataset_label(path)} — nDCG@10, {len(common)} queries", "",
             "| Mode | Mean | 95% CI |", "|---|---|---|"]
    for m in modes:
        xs = [by_mode[m][q] for q in common]
        lo, hi = bootstrap_ci(xs, rng)
        lines.append(f"| {m} | {mean(xs):.4f} | [{lo:.4f}, {hi:.4f}] |")
    lines += ["", "| Comparison | Mean difference | 95% CI | p (paired permutation) | Verdict |",
              "|---|---|---|---|---|"]
    for a, b in COMPARISONS:
        if a not in by_mode or b not in by_mode:
            continue
        diffs = [by_mode[a][q] - by_mode[b][q] for q in common]
        lo, hi = bootstrap_ci(diffs, rng)
        p = permutation_p(diffs, rng)
        if lo > 0:
            verdict = f"{a} better"
        elif hi < 0:
            verdict = f"{b} better"
        else:
            verdict = "no significant difference"
        lines.append(f"| {a} − {b} | {mean(diffs):+.4f} | [{lo:+.4f}, {hi:+.4f}] "
                     f"| {p:.4f} | {verdict} |")
    lines.append("")
    return lines


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("csv", nargs="+", type=Path)
    ap.add_argument("--md", type=Path, help="also write the report here")
    args = ap.parse_args()
    out = [f"Bootstrap: {B} resamples; permutation test: {B} sign flips; "
           f"seed {SEED}. Generated by tests/eval/significance.py.", ""]
    for path in args.csv:
        out += report(path)
    text = "\n".join(out)
    print(text)
    if args.md:
        args.md.write_text(text + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
