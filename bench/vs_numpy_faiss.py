#!/usr/bin/env python3
"""Exact top-k search: cRAG (via the crag Python binding) vs NumPy vs FAISS.

Same random unit vectors (dim 1024, float32, fixed seed) for every engine;
each engine runs in its own subprocess so its peak RSS is its own. For each
corpus size N it reports per-query latency P50 / P95 for top-10 cosine
search over QUERIES queries, build time, and peak RSS, and checks that all
engines return the same top-10 ids (an exact search must agree; a faster
engine that returns different results would not be a fair comparison).

    python3 bench/vs_numpy_faiss.py [--sizes 10000 100000] [--md OUT]

Needs: the crag package (pip install .), numpy, and faiss-cpu.
What it measures: the cRAG *index* (SQLite BLOB scan + exact cosine), not
embedding or chunking.
"""

from __future__ import annotations

import argparse
import json
import platform
import resource
import subprocess
import sys
import time

DIM = 1024
K = 10
QUERIES = 200
SEED = 20261109


def data(n: int):
    import numpy as np
    rng = np.random.default_rng(SEED)
    x = rng.standard_normal((n, DIM), dtype=np.float32)
    x /= np.linalg.norm(x, axis=1, keepdims=True)
    q = rng.standard_normal((QUERIES, DIM), dtype=np.float32)
    q /= np.linalg.norm(q, axis=1, keepdims=True)
    return x, q


def percentile(xs, p):
    xs = sorted(xs)
    return xs[min(len(xs) - 1, int(round(p / 100 * (len(xs) - 1))))]


def run_engine(engine: str, n: int) -> dict:
    """Runs inside the child process."""
    import numpy as np
    x, q = data(n)
    t0 = time.perf_counter()
    if engine == "crag":
        import crag
        idx = crag.Index(":memory:")
        idx.add_many((f"d{i}", f"chunk {i}", x[i]) for i in range(n))
        search = lambda v: [int(h.source[1:]) for h in idx.search(vector=v, k=K, mode="cosine")]
    elif engine == "numpy":
        search = lambda v: [int(i) for i in np.argsort(-(x @ v))[:K]]
    elif engine == "faiss":
        import faiss
        faiss.omp_set_num_threads(1)          # one query at a time, one core
        index = faiss.IndexFlatIP(DIM)
        index.add(x)
        search = lambda v: [int(i) for i in index.search(v[None, :], K)[1][0]]
    else:
        raise SystemExit(f"unknown engine {engine}")
    build_s = time.perf_counter() - t0

    lat, ids = [], []
    for v in q:
        t = time.perf_counter()
        ids.append(search(np.ascontiguousarray(v)))
        lat.append((time.perf_counter() - t) * 1000)
    rss_mb = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss / 1024
    return {"engine": engine, "n": n, "build_s": build_s,
            "p50_ms": percentile(lat, 50), "p95_ms": percentile(lat, 95),
            "rss_mb": rss_mb, "ids": ids}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--sizes", type=int, nargs="+", default=[10_000, 100_000])
    ap.add_argument("--md", help="also write the table to this file")
    ap.add_argument("--child", nargs=2, help=argparse.SUPPRESS)
    args = ap.parse_args()
    if args.child:
        print(json.dumps(run_engine(args.child[0], int(args.child[1]))))
        return 0

    rows = []
    for n in args.sizes:
        results = {}
        for engine in ("crag", "numpy", "faiss"):
            out = subprocess.run([sys.executable, __file__, "--child", engine, str(n)],
                                 capture_output=True, text=True, check=True).stdout
            results[engine] = json.loads(out.strip().splitlines()[-1])
        ref = results["numpy"]["ids"]
        for engine, r in results.items():
            r["agree"] = sum(a == b for a, b in zip(r["ids"], ref)) / len(ref)
            rows.append(r)

    import numpy
    import faiss
    head = (f"Exact top-{K} cosine, dim {DIM}, {QUERIES} queries, one query at a time; "
            f"{platform.processor() or platform.machine()}, Python {platform.python_version()}, "
            f"NumPy {numpy.__version__}, FAISS {faiss.__version__} (1 thread); "
            f"generated by bench/vs_numpy_faiss.py on {time.strftime('%Y-%m-%d')}.")
    lines = [head, "",
             "| N | Engine | P50 ms | P95 ms | Build s | Peak RSS MB | Same top-10 as NumPy |",
             "|---|---|---|---|---|---|---|"]
    for r in rows:
        lines.append(f"| {r['n']:,} | {r['engine']} | {r['p50_ms']:.2f} | {r['p95_ms']:.2f} "
                     f"| {r['build_s']:.2f} | {r['rss_mb']:.0f} | {r['agree']:.0%} |")
    text = "\n".join(lines)
    print(text)
    if args.md:
        with open(args.md, "w") as f:
            f.write(text + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
